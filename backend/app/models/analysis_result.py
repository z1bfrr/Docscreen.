from sqlalchemy import Column, String, Integer, Float, DateTime, Text, JSON, ForeignKey
from sqlalchemy.orm import relationship
from datetime import datetime
from app.core.database import Base

class AnalysisResult(Base):
    __tablename__ = "analysis_results"
    id = Column(String(36), primary_key=True)
    document_id = Column(String(36), ForeignKey("documents.id"), nullable=False)
    status = Column(String(32), default="pending")
    error_message = Column(Text)
    document_type = Column(String(128))
    classification_confidence = Column(Float)
    matched_template = Column(String(64))
    quality_score = Column(Float)
    quality_details = Column(JSON)
    ocr_status = Column(String(32), default="pending")
    ocr_avg_confidence = Column(Float)
    template_similarity = Column(Float)
    layout_details = Column(JSON)
    tamper_score = Column(Float)
    tamper_details = Column(JSON)
    forensic_heatmap_path = Column(String(512))
    qr_status = Column(String(32))
    qr_details = Column(JSON)
    anomaly_score = Column(Float)
    anomaly_label = Column(String(32))
    risk_score = Column(Integer)
    risk_label = Column(String(32))
    risk_breakdown = Column(JSON)
    metadata_anomaly_score = Column(Float)
    metadata_details = Column(JSON)
    consistency_details = Column(JSON)
    pipeline_version = Column(String(16))
    model_version = Column(String(16))
    analysis_steps = Column(JSON)
    review_status = Column(String(32), default="pending")
    created_at = Column(DateTime, default=datetime.utcnow)
    completed_at = Column(DateTime)
    document = relationship("Document", back_populates="analysis")
    ocr_fields = relationship("OcrField", back_populates="analysis")
    findings = relationship("Finding", back_populates="analysis")
    risk_scores = relationship("RiskScore", back_populates="analysis")
    reviews = relationship("Review", back_populates="analysis")
